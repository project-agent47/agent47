import { test, expect } from '@playwright/test';
test('home controls, filters, folder grant, mode guidance, create and stop', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByLabel('开始任务', { exact: true })).toBeDisabled();
  await page.getByRole('button', { name: '审阅一个项目' }).click();
  await expect(page.getByLabel('任务目标')).toHaveValue(/查看项目结构/);
  await page.getByRole('button', { name: '整理一份成果' }).click();
  await expect(page.getByLabel('任务指导')).toHaveValue('deliver');
  await page.getByRole('button', { name: '想清楚再行动' }).click();
  await expect(page.getByLabel('任务指导')).toHaveValue('general');
  await page.getByRole('button', { name: '选择项目目录' }).click();
  await expect(page.getByLabel('移除目录授权')).toBeVisible();
  await page.getByLabel('移除目录授权').click();
  await page.getByLabel('搜索任务').fill('No matching result 987');
  await expect(page.getByText('没有匹配的任务')).toBeVisible();
  await page.getByRole('button', { name: '清除筛选' }).click();
  await page.getByRole('button', { name: '进行中', exact: true }).click();
  await expect(page.getByText('没有匹配的任务')).toBeVisible();
  await page.getByRole('button', { name: '待审阅 1', exact: true }).click();
  await expect(page.locator('.task-row')).toHaveCount(1);
  await page.getByRole('button', { name: '全部', exact: true }).click();
  await page.getByLabel('任务目标').fill('Verify preview cancellation');
  await page.getByLabel('开始任务', { exact: true }).click();
  await page.getByRole('button', { name: '停止任务' }).click();
  await expect(page.locator('.task-title .status')).toHaveText('已停止');
  await page.getByRole('button', { name: '带入新任务' }).click();
  await expect(page.getByLabel('任务目标')).toHaveValue('Verify preview cancellation');
  await page.getByLabel('开始任务', { exact: true }).click();
  await expect(page.getByText('这是交互预览，没有调用模型或读取文件。', { exact: false })).toBeVisible();
  await expect(page.locator('.task-title .status')).toHaveText('已完成');
});
test('approval, inspector, artifact dialog keyboard trap, source and download', async ({ page }) => {
  await page.goto('/');
  await page.locator('.task-row').first().click();
  await expect(page.getByRole('button', { name: '批准创建' })).toBeVisible();
  await page.getByLabel('显示执行详情').click();
  await expect(page.getByRole('heading', { name: '执行详情' })).toBeVisible();
  await page.getByLabel('关闭执行详情').click();
  await page.getByLabel('切换深色模式').click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.screenshot({ path: '.qa/task-approval-dark.png', animations: 'disabled' });
  await page.getByLabel('切换浅色模式').click();
  await page.screenshot({ path: '.qa/task-approval-light.png', animations: 'disabled' });
  await page.getByRole('button', { name: '批准创建' }).click();
  await expect(page.locator('.task-title .status')).toHaveText('已完成');
  await page.getByRole('button', { name: '成果库', exact: true }).click();
  await page.locator('.artifact-card').click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByLabel('关闭成果预览')).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(page.getByRole('button', { name: '下载示例文件' })).toBeFocused();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '下载示例文件' }).click();
  expect((await download).suggestedFilename()).toBe('desktop-checklist.md');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.locator('.artifact-card').click();
  await page.getByRole('button', { name: '查看来源任务' }).click();
  await expect(page.locator('.task-title h1')).toHaveText(/整理 Agent47/);
});
